class Synth:
    """Builds a SYNTHETIC log record by record."""

    def __init__(self):
        self.r = [{"type": "meta", "t": 0, "schema": "selftest.v1", "run_id": "synthetic_run"}]

    def ev(self, t, step, name, **kw):
        self.r.append({"type": "event", "t": t, "step": step, "name": name, **kw})

    def status(self, t, left, right, front=999, rear=999, flags=8):
        self.r.append({"type": "status", "t": t, "uptime_ms": int(t * 1000), "left": left, "right": right,
                       "front_cm": front, "rear_cm": rear, "flags": flags})

    def pose(self, t, x, z, yaw):
        self.r.append({"type": "pose", "t": t, "tracking": "normal", "x": x, "z": z, "yaw_deg": yaw})

    def cmd(self, t, step, mode, left=0, right=0):
        self.r.append({"type": "cmd", "t": t, "step": step, "mode": mode, "left": left, "right": right})

    def end(self, t, step, ok=True):
        self.ev(t, step, "step_end", pass_=ok) if False else self.r.append(
            {"type": "event", "t": t, "step": step, "name": "step_end", "pass": ok, "reason": "ok", "metrics": {}})


def wheels_off(s, hz=5.0, applied_scale=1.0, t0=0.0):
    t = t0
    for ph, (l, r) in [("forward", (110, 110)), ("back", (-110, -110)), ("spin_left", (-110, 110)), ("spin_right", (110, -110))]:
        s.ev(t, "wheels_off", "phase_start", phase=ph, left=l, right=r)
        k = 0
        while k * (1 / hz) < 1.6:
            s.status(t + k / hz, round(l * applied_scale), round(r * applied_scale))
            k += 1
        s.ev(t + 1.6, "wheels_off", "phase_end", phase=ph)
        k = 0
        while k / hz < 0.7:                      # the ESP32 keeps sending status while the rover rests
            s.status(t + 1.6 + k / hz, 0, 0)
            k += 1
        t += 2.3
    s.end(t, "wheels_off")
    return t


def watchdog(s, t0, stop_after=0.3, flag=True, resume=True):
    for k in range(6):
        s.status(t0 + k * 0.2, 110, 110)
    ts = t0 + 1.2
    s.ev(ts, "watchdog", "watchdog_suspend")
    s.status(ts + 0.1, 110, 110)
    s.status(ts + stop_after, 0, 0, flags=9 if flag else 8)
    s.status(ts + stop_after + 0.2, 0, 0, flags=9 if flag else 8)
    tr = ts + 1.5
    s.ev(tr, "watchdog", "watchdog_resume")
    if resume:
        s.status(tr + 0.2, 110, 110)
    s.end(tr + 1, "watchdog")


def forward_back(s, t0=0.0, fwd=1.0, drift=0.0, ret=0.0):
    s.ev(t0, "forward_back", "leg_start", x=0, z=0, yaw_deg=0)
    for k in range(11):
        f = fwd * k / 10
        s.pose(t0 + k * 0.5, drift * k / 10, -f, 0)
    s.ev(t0 + 6, "forward_back", "fwd_end", x=drift, z=-fwd, yaw_deg=0)
    for k in range(11):
        s.pose(t0 + 6 + k * 0.5, drift * (1 - k / 10), -fwd * (1 - k / 10), 0)
    s.ev(t0 + 12, "forward_back", "back_end", x=0, z=-ret, yaw_deg=0)
    s.end(t0 + 12, "forward_back")


def square(s, t0, final_err=0.05, final_yaw=3.0):
    s.ev(t0, "square", "leg_start", leg=0, x=1.0, z=1.0, yaw_deg=10.0)
    for i in range(4):
        last = i == 3
        s.ev(t0 + 10 * (i + 1), "square", "turn_end", leg=i, x=1.0 + (final_err if last else 1.5), z=1.0, yaw_deg=10.0 + (final_yaw if last else 90 * (i + 1)))
    s.end(t0 + 41, "square")


def spin(s, t0, total=360.0, stop_at=6.0):
    s.ev(t0, "spin", "spin_start", x=0, z=0, yaw_deg=0)
    steps = 40
    for k in range(steps + 1):
        yaw = (total * k / steps + 180) % 360 - 180   # wrapped like ARKit yaw
        s.pose(t0 + stop_at * k / steps, 0, 0, yaw)
    s.cmd(t0 + stop_at, "spin", "stop")
    s.ev(t0 + stop_at + 1, "spin", "spin_end", x=0, z=0, yaw_deg=total % 360)
    s.end(t0 + stop_at + 1, "spin")


def obstacle(s, t0, min_front=33, clamp_lin=0, flag2=True, turn=110, rev=-110):
    s.ev(t0, "obstacle", "approach_start")
    for k in range(4):
        s.status(t0 + k * 0.2, 90, 90, front=120 - 20 * k)
    s.status(t0 + 0.8, 0, 0, front=min_front)
    s.ev(t0 + 1.0, "obstacle", "approach_stopped", reason="guard_stop", front_cm=min_front)
    s.ev(t0 + 2.2, "obstacle", "approach_end", stop_reason="guard_stop", min_front_cm=min_front)
    b = t0 + 5
    s.ev(b, "obstacle", "blocked_start", front_cm=15)
    for k in range(6):
        s.status(b + 0.2 * k, clamp_lin, clamp_lin, front=15, flags=8 | (2 if flag2 else 0))
    s.ev(b + 1.0, "obstacle", "clamp_forward_result")
    for k in range(5):
        s.status(b + 1.0 + 0.2 * k, -turn, turn, front=15, flags=10)
    s.ev(b + 1.8, "obstacle", "blocked_spin_result")
    for k in range(6):
        s.status(b + 1.8 + 0.2 * k, rev, rev, front=18, flags=10)
    s.ev(b + 2.8, "obstacle", "reverse_result")
    s.end(b + 2.8, "obstacle")


def run(s, **kw):
    return mr.analyze(s.r, TH, **kw)


def check(summary, step, name_part):
    return next(c for c in summary["steps"][step]["checks"] if name_part in c["name"])


class MathTests(unittest.TestCase):
    def test_shortest_delta_wraps(self):
        self.assertAlmostEqual(mr.shortest_delta(170, -170), 20)
        self.assertAlmostEqual(mr.shortest_delta(-170, 170), -20)
        self.assertAlmostEqual(mr.shortest_delta(0, 90), 90)

    def test_forward_unit_and_lateral_sign(self):
        u = mr.forward_unit(0)
        self.assertAlmostEqual(u[1], -1)
        u90 = mr.forward_unit(90)
        self.assertAlmostEqual(u90[0], -1)
        p0 = {"x": 0, "z": 0}
        self.assertAlmostEqual(mr.lateral(p0, u, {"x": -0.2, "z": -1}), 0.2)   # left of a -z heading is -x
        self.assertAlmostEqual(mr.along(p0, u, {"x": 0, "z": -1}), 1)


class StepTests(unittest.TestCase):
    def test_all_pass_on_clean_synthetic_run(self):
        s = Synth()
        t = wheels_off(s)
        watchdog(s, t + 1)
        forward_back(s, 50)
        square(s, 70)
        spin(s, 120)
        obstacle(s, 140)
        r = run(s)
        for name in mr.STEPS:
            self.assertEqual(r["steps"][name]["status"], "pass", (name, r["steps"][name]["checks"]))
        self.assertEqual(r["overall"], "pass")
        self.assertAlmostEqual(r["steps"]["spin"]["metrics"]["spin_total_deg"], 360, places=3)

    def test_wheels_off_detects_weak_motor_and_low_status_rate(self):
        s = Synth(); wheels_off(s, applied_scale=0.5)
        self.assertEqual(run(s)["steps"]["wheels_off"]["status"], "fail")
        s = Synth(); wheels_off(s, hz=2.5)
        self.assertEqual(check(run(s), "wheels_off", "status rate")["status"], "fail")

    def test_wheels_off_no_status_is_no_data_not_pass(self):
        s = Synth()
        s.ev(0, "wheels_off", "phase_start", phase="forward", left=110, right=110)
        s.ev(1.6, "wheels_off", "phase_end", phase="forward")
        s.end(2, "wheels_off")
        r = run(s)
        self.assertEqual(r["steps"]["wheels_off"]["status"], "no_data")
        self.assertNotEqual(r["overall"], "pass")

    def test_watchdog_slow_missing_flag_and_no_resume(self):
        s = Synth(); watchdog(s, 0, stop_after=0.9)
        self.assertEqual(check(run(s), "watchdog", "read 0")["status"], "fail")
        s = Synth(); watchdog(s, 0, flag=False)
        self.assertEqual(check(run(s), "watchdog", "flag")["status"], "fail")
        s = Synth(); watchdog(s, 0, resume=False)
        self.assertEqual(check(run(s), "watchdog", "resume")["status"], "no_data")

    def test_forward_back_drift_distance_and_return(self):
        s = Synth(); forward_back(s, drift=0.25)
        r = run(s)
        self.assertEqual(check(r, "forward_back", "lateral")["status"], "fail")
        self.assertAlmostEqual(check(r, "forward_back", "lateral")["value"], 0.25, places=3)
        s = Synth(); forward_back(s, fwd=0.7)
        self.assertEqual(check(run(s), "forward_back", "distance error")["status"], "fail")
        s = Synth(); forward_back(s, ret=0.3)
        self.assertEqual(check(run(s), "forward_back", "return error")["status"], "fail")
        s = Synth(); forward_back(s, fwd=1.04, ret=0.05, drift=0.03)
        self.assertEqual(run(s)["steps"]["forward_back"]["status"], "pass")

    def test_forward_back_uses_start_heading_not_world_axes(self):
        s = Synth()
        s.ev(0, "forward_back", "leg_start", x=2, z=3, yaw_deg=90)       # faces -x
        s.ev(5, "forward_back", "fwd_end", x=1.0, z=3, yaw_deg=90)       # moved 1 m along heading
        s.pose(1, 1.5, 3, 90)
        s.ev(10, "forward_back", "back_end", x=2.02, z=3, yaw_deg=90)
        s.end(10, "forward_back")
        r = run(s)
        self.assertAlmostEqual(r["steps"]["forward_back"]["metrics"]["forward_distance_m"], 1.0, places=3)
        self.assertEqual(r["steps"]["forward_back"]["status"], "pass")

    def test_square_final_error(self):
        s = Synth(); square(s, 0, final_err=0.4)
        self.assertEqual(run(s)["steps"]["square"]["status"], "fail")
        s = Synth(); square(s, 0, final_err=0.10, final_yaw=-4)
        self.assertEqual(run(s)["steps"]["square"]["status"], "pass")

    def test_square_incomplete_is_no_data(self):
        s = Synth()
        s.ev(0, "square", "leg_start", leg=0, x=0, z=0, yaw_deg=0)
        s.end(5, "square", ok=False)
        self.assertEqual(run(s)["steps"]["square"]["status"], "no_data")

    def test_spin_unwraps_yaw_and_flags_undershoot(self):
        s = Synth(); spin(s, 0, total=360)
        self.assertEqual(run(s)["steps"]["spin"]["status"], "pass")
        s = Synth(); spin(s, 0, total=300)
        r = run(s)
        self.assertEqual(check(r, "spin", "yaw error")["status"], "fail")
        self.assertAlmostEqual(check(r, "spin", "yaw error")["value"], 60, places=2)
        s = Synth(); spin(s, 0, stop_at=40)
        self.assertEqual(check(run(s), "spin", "spin time")["status"], "fail")

    def test_obstacle_failures(self):
        s = Synth(); obstacle(s, 0, min_front=6)
        self.assertEqual(check(run(s), "obstacle", "closest front")["status"], "fail")
        s = Synth(); obstacle(s, 0, clamp_lin=80)
        self.assertEqual(check(run(s), "obstacle", "clamped")["status"], "fail")
        s = Synth(); obstacle(s, 0, flag2=False)
        self.assertEqual(check(run(s), "obstacle", "flag (2)")["status"], "fail")
        s = Synth(); obstacle(s, 0, turn=10)
        self.assertEqual(check(run(s), "obstacle", "turning")["status"], "fail")
        s = Synth(); obstacle(s, 0, rev=20)
        self.assertEqual(check(run(s), "obstacle", "reverse")["status"], "fail")

    def test_incidents_counted_and_abort_makes_overall_fail(self):
        s = Synth(); wheels_off(s)
        s.ev(30, "forward_back", "tracking_incident", tracking="limited")
        s.ev(31, "forward_back", "ble_disconnect")
        s.ev(32, "forward_back", "abort", reason="ble_disconnected")
        r = run(s)
        self.assertEqual(check(r, "incidents", "tracking")["value"], 1)
        self.assertEqual(check(r, "incidents", "BLE")["value"], 1)
        self.assertEqual(r["steps"]["incidents"]["status"], "fail")
        self.assertEqual(r["aborts"], ["ble_disconnected"])
        self.assertEqual(r["overall"], "fail")

    def test_steps_not_in_log_are_not_run(self):
        s = Synth(); wheels_off(s)
        r = run(s)
        self.assertEqual(r["steps"]["spin"]["status"], "not_run")
        self.assertEqual(r["steps"]["obstacle"]["status"], "not_run")
        self.assertEqual(r["overall"], "incomplete")

    def test_app_verdict_is_carried_separately(self):
        s = Synth(); wheels_off(s)
        self.assertTrue(run(s)["steps"]["wheels_off"]["app_verdict"]["pass"])


class CliTests(unittest.TestCase):
    def write(self, lines):
        f = tempfile.NamedTemporaryFile("w", suffix=".jsonl", delete=False)
        f.write("\n".join(lines) + "\n"); f.close()
        self.addCleanup(os.unlink, f.name)
        return f.name

    def test_cli_prints_table_writes_summary_and_exit_codes(self):
        s = Synth(); t = wheels_off(s); watchdog(s, t + 1)
        path = self.write([json.dumps(r) for r in s.r] + ["{not json"])
        out = tempfile.NamedTemporaryFile(suffix=".json", delete=False); out.close()
        self.addCleanup(os.unlink, out.name)
        import io, contextlib
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            code = mr.main([path, "--summary", out.name])
        text = buf.getvalue()
        self.assertEqual(code, 1)                      # steps 2 to 5 are not in this log: incomplete is not a pass
        self.assertIn("OVERALL: INCOMPLETE", text)
        self.assertIn("to be calibrated by Steven, not measured", text)
        self.assertIn("1 unreadable log lines", text)
        with open(out.name) as fh:
            summary = json.load(fh)
        self.assertEqual(summary["schema"], "motion_report.v1")
        self.assertEqual(summary["bad_log_lines"], 1)
        self.assertEqual(summary["steps"]["wheels_off"]["status"], "pass")

    def test_cli_bad_input_exit_2(self):
        import contextlib, io
        with contextlib.redirect_stderr(io.StringIO()):
            self.assertEqual(mr.main(["/nonexistent/file.jsonl"]), 2)
            self.assertEqual(mr.main([self.write(["garbage"])]), 2)


